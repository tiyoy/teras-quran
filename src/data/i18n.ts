export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let raw = DICT[locale]?.[key] ?? DICT.id[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      raw = raw.replaceAll(`{${k}}`, String(v));
    }
  }
  return raw;
}
